# ── Helpers ───────────────────────────────────────────────────────────────────

def lines_to_latlons(gdf):
    """Return flat lat/lon lists (None-separated) for Scattermap."""
    lats, lons = [], []
    for geom in gdf.geometry:
        for part in (geom.geoms if hasattr(geom, "geoms") else [geom]):
            xs, ys = part.xy
            lons += list(xs) + [None]
            lats += list(ys) + [None]
    return lats, lons

