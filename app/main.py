# ── Map builder ───────────────────────────────────────────────────────────────
def update(year):
    traces = []

    # 1 · Ward flooding choropleth (2005-2022)
    if year in _year_col:
        col = _year_col[year]
        wf = _df[["ward_num", col]].copy()
        wf.columns = ["ward_num", "count"]
        wf["count"] = pd.to_numeric(wf["count"], errors="coerce").fillna(0)
        z_ward, locs_ward = wf["count"].tolist(), wf["ward_num"].tolist()
        opacity_ward = 0.55
    else:
        z_ward, locs_ward, opacity_ward = [0] * len(wards), wards["ward_num"].tolist(), 0.0
    ward_customdata = [[_ward_name.get(w, str(w))] for w in locs_ward]

    traces.append(go.Choroplethmap(
        geojson=ward_geojson, locations=locs_ward, z=z_ward,
        featureidkey="id",
        customdata=ward_customdata,
        colorscale="YlOrRd", zmin=0, zmax=WARD_FLOOD_MAX,
        marker=dict(opacity=opacity_ward, line=dict(width=0.5, color="#888")),
        name=f"Ward basement floods ({WARD_FLOOD_YEARS[0]}–{WARD_FLOOD_YEARS[-1]})",
        showlegend=True, showscale=bool(year in _year_col),
        hovertemplate="<b>%{customdata[0]}</b><br>Basement floods: %{z:.0f}<extra></extra>",
        colorbar=dict(title=dict(text="Ward<br>basement<br>floods", font=dict(color="white")),
                      thickness=12, len=0.35, x=1.0, y=0.75, tickfont=dict(color="white")),
    ))

    # 2 · Neighbourhood flood reports (2013-2017)
    yr_s = str(year)
    if yr_s in flood_rep.columns:
        z_rep = pd.to_numeric(flood_rep[yr_s], errors="coerce").fillna(0).tolist()
        op_rep = 0.65
    else:
        z_rep, op_rep = [0] * len(flood_rep), 0.0

    traces.append(go.Choroplethmap(
        geojson=flood_rep_geojson,
        locations=list(range(len(flood_rep))), z=z_rep,
        featureidkey="id",
        customdata=[[n] for n in _flood_rep_names],
        colorscale=[[0, "rgba(0,0,0,0)"], [0.01, "#ffffcc"],
                    [0.5, "#fd8d3c"], [1, "#bd0026"]],
        zmin=0, zmax=FLOOD_REP_MAX,
        marker=dict(opacity=op_rep, line=dict(width=0.8, color="#ff6b6b")),
        name=f"Neighbourhood flood reports ({min(FLOOD_REP_YEARS)}–{max(FLOOD_REP_YEARS)})",
        showlegend=True, showscale=bool(yr_s in flood_rep.columns),
        hovertemplate="<b>%{customdata[0]}</b><br>Flood reports: %{z:.0f}<extra></extra>",
        colorbar=dict(title=dict(text="Neighbourhood<br>flood reports", font=dict(color="white")),
                      thickness=12, len=0.35, x=1.0, y=0.3, tickfont=dict(color="white")),
    ))

    # 3 · Trunk sewers built by this year
    mask = trunk["install_year"].notna() & (trunk["install_year"] <= year)
    built = trunk[mask]
    if len(built):
        lats, lons = lines_to_latlons(built)
        traces.append(go.Scattermap(
            lat=lats, lon=lons, mode="lines",
            line=dict(color="#e8a838", width=1.5),
            name=f"Trunk sewers (built ≤ {year})",
            hovertemplate="<b>Trunk sewer</b><br>Major underground conduits constructed on or before %{meta}<extra></extra>",
            meta=year,
        ))

    # 4 · Lost rivers — cyan if still flowing, grey if already buried
    still_lats, still_lons = [], []
    buried_lats, buried_lons = [], []
    for last_yr, lats_chunk in _river_lats.items():
        if last_yr == "all":
            continue
        lons_chunk = _river_lons[last_yr]
        if last_yr >= year:
            still_lats += lats_chunk
            still_lons += lons_chunk
        else:
            buried_lats += lats_chunk
            buried_lons += lons_chunk

    if still_lats:
        traces.append(go.Scattermap(
            lat=still_lats, lon=still_lons, mode="lines",
            line=dict(color="#4fc3f7", width=2.0),
            name=f"Lost rivers — still surface ({RIVER_YEAR_MIN}–{RIVER_YEAR_MAX})",
            hovertemplate="<b>Lost river (still flowing)</b><br>Visible on historical maps in %{meta}.<br>Dataset covers burial years %{customdata[0]}–%{customdata[1]}<extra></extra>",
            meta=year,
            customdata=[[RIVER_YEAR_MIN, RIVER_YEAR_MAX]] * len(still_lats),
        ))
    if buried_lats:
        traces.append(go.Scattermap(
            lat=buried_lats, lon=buried_lons, mode="lines",
            line=dict(color="#ce93d8", width=1.8),
            opacity=0.85,
            name=f"Lost rivers — already buried ({RIVER_YEAR_MIN}–{RIVER_YEAR_MAX})",
            hovertemplate="<b>Lost river (buried)</b><br>Channelled underground before %{meta}.<br>Dataset covers burial years %{customdata[0]}–%{customdata[1]}<extra></extra>",
            meta=year,
            customdata=[[RIVER_YEAR_MIN, RIVER_YEAR_MAX]] * len(buried_lats),
        ))

    fig = go.Figure(data=traces)

    if _precip is not None and year in _precip.index:
        row = _precip.loc[year]
        fig.add_annotation(
            text=(
                f"<b>Precipitation {year}</b><br>"
                f"Total: {row['precip_mm']:.0f} mm<br>"
                f"Rain: {row['rain_mm']:.0f} mm  Snow: {row['snow_cm']:.0f} cm<br>"
                f"Heavy-rain days (>25 mm): {int(row['heavy_days'])}"
            ),
            xref="paper", yref="paper",
            x=0.01, y=0.01, xanchor="left", yanchor="bottom",
            showarrow=False, align="left",
            font=dict(color="#ccc", size=11),
            bgcolor="rgba(13,17,23,0.78)", borderpad=6,
        )

    fig.update_layout(
        map_style="carto-darkmatter",
        map_center={"lat": 43.72, "lon": -79.40},
        map_zoom=10,
        paper_bgcolor="#0d1117",
        margin=dict(l=0, r=0, t=0, b=0),
        legend=dict(bgcolor="rgba(13,17,23,0.85)", font=dict(color="white", size=11),
                    x=0.01, y=0.99, xanchor="left", yanchor="top"),
        uirevision="constant",
    )
    return fig


# ── River-change figure for a transition period ──────────────────────────────

def build_change_fig(before_year, after_year):
    """Plotly map: gray=already buried, orange=newly buried, cyan=still flowing."""
    already_lats, already_lons = [], []
    new_lats,     new_lons     = [], []
    still_lats,   still_lons   = [], []
    for last_yr, lats_chunk in _river_lats.items():
        if last_yr == "all":
            continue
        lons_chunk = _river_lons[last_yr]
        if last_yr < before_year:
            already_lats += lats_chunk; already_lons += lons_chunk
        elif last_yr <= after_year:
            new_lats     += lats_chunk; new_lons     += lons_chunk
        else:
            still_lats   += lats_chunk; still_lons   += lons_chunk

    traces = []
    if already_lats:
        traces.append(go.Scattermap(
            lat=already_lats, lon=already_lons, mode="lines",
            line=dict(color="#3a3a3a", width=1.0), name="Buried before",
            hovertemplate="<b>Buried before this period</b><extra></extra>",
        ))
    if still_lats:
        traces.append(go.Scattermap(
            lat=still_lats, lon=still_lons, mode="lines",
            line=dict(color="#4fc3f7", width=1.5), name="Still flowing after",
            hovertemplate="<b>Still flowing after this period</b><extra></extra>",
        ))
    if new_lats:
        traces.append(go.Scattermap(
            lat=new_lats, lon=new_lons, mode="lines",
            line=dict(color="#ff7043", width=3.0),
            name=f"Buried {before_year}–{after_year}",
            hovertemplate=f"<b>Buried {before_year}–{after_year}</b><extra></extra>",
        ))

    fig = go.Figure(data=traces)
    fig.update_layout(
        map_style="carto-darkmatter",
        map_center={"lat": 43.68, "lon": -79.38}, map_zoom=10,
        paper_bgcolor="#0d1117",
        margin=dict(l=0, r=0, t=0, b=0),
        legend=dict(bgcolor="rgba(13,17,23,0.85)", font=dict(color="white", size=10),
                    x=0.01, y=0.99, xanchor="left", yanchor="top"),
        uirevision=f"{before_year}-{after_year}",
    )
    return fig


